MutexHelper::MutexHelper ()
{
  m_mutex = new common::aox::InheritMutex;
}

MutexHelper::~MutexHelper ()
{
  delete m_mutex;
  m_mutex = nullptr;
}

bool MutexHelper::lock()
{
  m_mutex->lock();
  return true;
}

bool MutexHelper::unlock()
{
  m_mutex->unlock();
  return true;
}
